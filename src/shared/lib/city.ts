/**
 * Предложный падеж названия города: «в Худжанде», но «в Душанбе».
 *
 * Наивное добавление «е» ломается на несклоняемых — Душанбе, Турсунзаде.
 * Используется и в заголовке витрины, и в ссылках подвала, поэтому живёт
 * в shared, а не копией в каждом виджете.
 */
export function inCity(name: string): string {
  const trimmed = name.trim();
  if (!trimmed) return '';

  const last = trimmed.slice(-1).toLowerCase();

  // Оканчивается на гласную — не склоняется
  if ('аеёиоуыэюя'.includes(last)) return trimmed;

  // Мягкий знак и «й» заменяются на «е»
  if (last === 'ь' || last === 'й') return `${trimmed.slice(0, -1)}е`;

  // Согласная — добавляем «е»: Худжанд → Худжанде, Бохтар → Бохтаре
  return `${trimmed}е`;
}
